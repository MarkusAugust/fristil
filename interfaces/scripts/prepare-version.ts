/**
 * Sets the version to be published in every file that carries it. It only
 * writes the files, and publishes nothing.
 *
 * A release is three things that must agree: the number in `package.json`,
 * the heading in `CHANGELOG.md`, and the tag in git. Set by hand, it is easy
 * to tag `v0.3.0` on a commit that still says `0.2.0`. The check in
 * `publish.yml` then stops the run, but only after the tag has been pushed,
 * and a pushed tag has to be removed again.
 *
 * Run with: bun run prepare-version <next version>
 */

import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { englishDate } from "./english-date.js"

const packageDir = fileURLToPath(new URL("../", import.meta.url))
const monorepoRoot = fileURLToPath(new URL("../../", import.meta.url))
const manifestPath = join(packageDir, "package.json")
const changelogPath = join(packageDir, "CHANGELOG.md")

const UNRELEASED = "## Unreleased"

function stop(message: string): never {
  console.error(message)
  process.exit(1)
}

const newVersion = process.argv[2]

if (!newVersion) {
  stop("Missing version number. Use: bun run prepare-version 0.4.0")
}

if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(newVersion)) {
  stop(`"${newVersion}" is not a version number of the form 0.3.0.`)
}

const manifest = await Bun.file(manifestPath).text()
const changelog = await Bun.file(changelogPath).text()

const { name: packageName, version: current } = JSON.parse(manifest) as {
  name: string
  version: string
}

if (!isHigher(newVersion, current)) {
  stop(`The version must be higher than ${current}, and ${newVersion} is not.`)
}

if (
  new RegExp(`^## ${newVersion.replace(/\./g, "\\.")}\\b`, "m").test(changelog)
) {
  stop(`The changelog already has a heading for ${newVersion}.`)
}

const start = changelog.indexOf(UNRELEASED)

if (start === -1) {
  stop(`Found no "${UNRELEASED}" in the changelog.`)
}

// What stands between "Unreleased" and the next version heading is what is
// being released. If it is empty, there is nothing to release, and an empty
// heading in the changelog is worse than no release.
const rest = changelog.slice(start + UNRELEASED.length)
const next = rest.search(/\n## \d/)
const content = (next === -1 ? rest : rest.slice(0, next)).trim()

if (content === "") {
  stop(
    '"Unreleased" is empty, so there is nothing to release. Write down what has changed first.',
  )
}

// The date is read in local time, not UTC. `toISOString` gave the day before
// when the version was set after midnight Norwegian time, and the changelog
// should carry the day the person releasing actually had.
const now = new Date()
const date = [
  now.getFullYear(),
  String(now.getMonth() + 1).padStart(2, "0"),
  String(now.getDate()).padStart(2, "0"),
].join("-")

// `web-types.json` carries the version too. The file is generated by
// generate-vocabulary.ts, and the build requires the file on disk to be
// byte for byte what the generator would write, so the version is written
// here rather than every release having to remember to run the generator.
// The check comes before the first write: when it stopped afterwards, the
// changelog, the manifest and bun.lock already carried the new number, and
// the next attempt refused because the version was taken.
const webTypesPath = join(monorepoRoot, "interfaces", "web-types.json")
let webTypes = ""
try {
  webTypes = readFileSync(webTypesPath, "utf8")
} catch {
  stop(
    "Found no web-types.json. Run bun --filter @lo-tek/interfaces vocabulary first.",
  )
}
const webTypesBefore = `"version": "${current}"`
if (!webTypes.includes(webTypesBefore)) {
  stop(
    `Found no version ${current} in web-types.json. Run bun --filter @lo-tek/interfaces vocabulary first.`,
  )
}

/*
 * The badge at the top of the presentation carries the version and the day
 * it came out.
 *
 * It said "LO-TEK 0.15.0 · 26 September 2026" while the package was at
 * 0.19.0, four versions behind, and nothing updated it. The presentation has
 * no build step, so it cannot fetch the value itself the way the
 * documentation now does; it has to be written, and `check-version.ts` fails
 * if it drifts again.
 *
 * The reading and the check stand here, with the other prechecks, for the
 * same reason as web-types above: when it stopped after the writes, the
 * changelog, the manifest and bun.lock already carried the new number, and
 * the next attempt refused because the version was taken.
 *
 * The data set in the dependency graph is left alone. It was checked on a
 * date of its own, and a number that was checked should not be set by a
 * script that has checked nothing.
 */
const deckPath = join(
  monorepoRoot,
  "presentation/design-system-architecture.html",
)
let deck = ""
try {
  deck = readFileSync(deckPath, "utf8")
} catch {
  stop(`Found no ${deckPath}. Has the presentation moved?`)
}

const badge = /(Design system architecture · LO-TEK )[^<·]+ · [^<·]+/
if (!badge.test(deck)) {
  stop(
    `Found no version badge in ${deckPath}. Is it still there, with the same name?`,
  )
}

/*
 * The Kotlin package has the same version, and is built from the npm package
 * with that number. If it lags behind, the Maven Central release fetches the
 * previous version from npm, and `check-version.ts` fails. The check comes
 * before the first write, as for web-types above.
 */
const kotlinPath = join(monorepoRoot, "kotlin/gradle.properties")
const kotlin = readFileSync(kotlinPath, "utf8")
const kotlinBefore = `\nversion=${current}\n`
if (!kotlin.includes(kotlinBefore)) {
  stop(`Found no version=${current} in ${kotlinPath}.`)
}

/*
 * `bun.lock` also carries the version of every workspace, and it is left
 * behind on the previous number. Tested with bun 1.3.14: this does not stop
 * `--frozen-lockfile`, which only compares how dependencies are resolved.
 * Publishing goes through either way.
 *
 * It is written anyway, because a lockfile that states the wrong version
 * misleads whoever reads it, and the gap only grows with every release.
 *
 * The value has to be set by hand. Neither `bun install`, `--lockfile-only`
 * nor `--force` updates it when only the version has changed. Only a full
 * regeneration does, and deleting the lockfile in a release would touch
 * resolutions that have nothing to do with it.
 *
 * The format check stands here, before the first write, like the others. It
 * used to come after the changelog and `package.json` had been written, and a
 * new version of Bun that writes the lockfile differently would then have
 * stopped the script with those two files already changed, and the next
 * attempt would have refused because `package.json` said the version was
 * taken.
 */
const lockPath = join(monorepoRoot, "bun.lock")
const lock = await Bun.file(lockPath).text()
const lockPattern = new RegExp(
  `("name":\\s*"${packageName}",\\s*\n\\s*"version":\\s*")[^"]+(")`,
)

if (!lockPattern.test(lock)) {
  stop(
    `Found no version of ${packageName} in bun.lock. Check the format before releasing.`,
  )
}

await Bun.write(
  changelogPath,
  changelog.replace(UNRELEASED, `${UNRELEASED}\n\n## ${newVersion} (${date})`),
)
await Bun.write(
  manifestPath,
  manifest.replace(`"version": "${current}"`, `"version": "${newVersion}"`),
)

await Bun.write(lockPath, lock.replace(lockPattern, `$1${newVersion}$2`))

writeFileSync(
  kotlinPath,
  kotlin.replace(kotlinBefore, `\nversion=${newVersion}\n`),
)

writeFileSync(
  webTypesPath,
  webTypes.replace(webTypesBefore, `"version": "${newVersion}"`),
)

const inEnglish = englishDate(date)

writeFileSync(deckPath, deck.replace(badge, `$1${newVersion} · ${inEnglish}`))
console.log(`The presentation badge now says ${newVersion}, ${inEnglish}.`)

/*
 * `agent/*.md` and `manifest/*.json` carry the version, and the generators
 * read it from `package.json`, which now has the new number. Without this
 * step it was `build` in `check` that wrote them, and "Generated files are
 * up to date" stopped on the files that still had the previous version, so
 * every release needed one more commit.
 *
 * This runs last, after every write a precheck can stop. If a generator
 * fails, the version is already set, and the message says what to run by
 * hand.
 */
for (const generator of ["generate-agent.ts", "generate-manifest.ts"]) {
  const result = Bun.spawnSync(["bun", join("scripts", generator)], {
    cwd: packageDir,
    stdio: ["inherit", "inherit", "inherit"],
  })
  if (result.exitCode !== 0) {
    stop(
      `${generator} failed. The version is already set to ${newVersion}. Run bun --filter @lo-tek/interfaces generate and see what stops.`,
    )
  }
}

console.log(`The version is set to ${newVersion}, dated ${date}.

To release it: every file that carries the version has been written, so one
commit is enough. "Generated files are up to date" in the check asks git whether the
build changed anything, and would otherwise stop on the files just written.

  git checkout -b release-${newVersion}
  git commit -am "Version ${newVersion}"
  bun run check
  git push -u origin release-${newVersion} && gh pr create --fill

Once the branch is merged, and not before:

  git checkout master && git pull
  bun run tag package`)

/** Compares two versions of the form 0.3.0, number by number. */
function isHigher(candidate: string, previous: string): boolean {
  const a = candidate.split(".").map(Number)
  const b = previous.split(".").map(Number)

  for (let i = 0; i < 3; i++) {
    if (a[i] !== b[i]) return a[i] > b[i]
  }

  return false
}
