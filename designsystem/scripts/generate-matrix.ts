/**
 * Writes `src/tokens/matrix-cells.ts`: LO-TEK's own colours, computed by the core.
 *
 * The colours are the contract (`color-contract.json`) applied to LO-TEK's
 * own brand colours, and the computation exists only in Rust. The result is
 * written as data, so `@lo-tek/interfaces/tokens` and `tokens.css` have the
 * colours without loading WebAssembly, in the browser too.
 *
 * The types are written as well: `Family` and `MatrixToken` are the names the
 * matrix emits, so a new family or role in the contract comes along by itself.
 *
 * Run with: bun scripts/generate-matrix.ts, or as part of `generate`.
 * Requires the core, built with `bun run core`. The core carries no data, so
 * it gets the colour contract here, and does not need the manifest that is
 * written afterwards.
 */

import { readFileSync, writeFileSync } from "node:fs"
import { loadCore } from "../src/diagnostics/core.js"

const contractText = readFileSync(
  new URL("../src/tokens/color-contract.json", import.meta.url),
  "utf8",
)
const contract: {
  families: string[]
  brands: Record<string, string>
  roles: Record<string, unknown>
  layers: Record<string, unknown>
  requirements: Record<string, number>
} = JSON.parse(contractText)
const core = loadCore(
  readFileSync(new URL("../core/lotek-core.wasm", import.meta.url)),
)
core.loadContract(contractText)
const { light, dark, violations } = core.buildTheme(contract.brands)

if (violations.length > 0) {
  console.error(
    "LO-TEK's own colours do not keep the promises in the colour contract:",
  )
  for (const v of violations)
    console.error(
      `  ${v.family}: ${v.promise} is ${v.ratio.toFixed(2)}:1, the requirement is ${v.required}:1`,
    )
  process.exit(1)
}

const names = Object.keys(light)
const file = `// Generated by scripts/generate-matrix.ts from the core and color-contract.json. Do not edit.

/** The families LO-TEK ships itself. A consumer can have others. */
export const FAMILIES = ${JSON.stringify(contract.families)} as const

export type Family = (typeof FAMILIES)[number]

/** LO-TEK's own brand colours. */
export const LOTEK_BRANDS: Record<Family, string> = ${JSON.stringify(contract.brands, null, 2)}

/** A role is a job a colour does, and it is the same in every family. */
export type Role = ${Object.keys(contract.roles)
  .map((r) => JSON.stringify(r))
  .join(" | ")}

/** Light or dark. A theme is one or the other, never both. */
export type Appearance = "light" | "dark"

type Spec = { lightness: Record<Appearance, number>; chroma: number }

/** Lightness and chroma share per role, in each appearance. */
export const ROLES: Record<Role, Spec> = ${JSON.stringify(contract.roles, null, 2)}

/** The page and the raised surface, which only the neutral family has. */
export const NEUTRAL_LAYERS: Record<"canvas" | "raised", Spec> = ${JSON.stringify(contract.layers, null, 2)}

/** The contrast requirements, with a margin above WCAG. Text is 4.5 and graphics 3. */
export const REQUIREMENT = ${JSON.stringify(contract.requirements)} as const

/** Every name the matrix emits. */
export type MatrixToken =
${names.map((n) => `  | ${JSON.stringify(n)}`).join("\n")}

/** LO-TEK's own colours in the light theme. */
export const lightCells: Record<MatrixToken, string> = ${JSON.stringify(light, null, 2)}

/** LO-TEK's own colours in the dark theme. */
export const darkCells: Record<MatrixToken, string> = ${JSON.stringify(dark, null, 2)}
`
writeFileSync(new URL("../src/tokens/matrix-cells.ts", import.meta.url), file)
console.log(
  `✓ The matrix: ${names.length} colours in each theme, computed by the core.`,
)
