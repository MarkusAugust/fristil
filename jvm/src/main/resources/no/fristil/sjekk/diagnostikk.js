  var fromCode = (code, hit) => Number.isInteger(code) && code > 0 && code <= 1114111 ? String.fromCodePoint(code) : hit;
  function decode(text) {
    return text.replace(/&(#x[0-9a-f]+|#[0-9]+|[a-z]+);/gi, (hit, code) => {
      const lower = code.toLowerCase();
      if (lower.startsWith("#x"))
        return fromCode(Number.parseInt(lower.slice(2), 16), hit);
      if (lower.startsWith("#"))
        return fromCode(Number.parseInt(lower.slice(1), 10), hit);
      return ENTITIES[lower] ?? hit;
    });
  }
  function fragment(href) {
    try {
      return decode(decodeURIComponent(href));
    } catch {
      return decode(href);
    }
  }
  var blank = (hit) => hit.replace(/[^\n]/g, " ");
  var TAG = /<(\/?)([a-z][a-z0-9-]*)(?=[\s/>])/gi;
  function* scan(source) {
    const pattern = new RegExp(TAG);
    for (let hit = pattern.exec(source);hit; hit = pattern.exec(source)) {
      const start = hit.index;
      const end = tagEnd(source, start + hit[0].length);
      if (end < 0)
        return;
      yield { closing: hit[1] === "/", name: hit[2].toLowerCase(), start, end };
      pattern.lastIndex = end + 1;
    }
  }
  var RAW_TEXT = new Set(["script", "style", "textarea", "template"]);
  function pageSource(text) {
    const ranges = [];
    const tagAt = /<(\/?)([a-z][a-z0-9-]*)(?=[\s/>])/iy;
    let i = 0;
    while (i < text.length) {
      const lt = text.indexOf("<", i);
      if (lt < 0)
        break;
      if (text.startsWith("<!--", lt)) {
        const close = text.indexOf("-->", lt + 4);
        const end = close < 0 ? text.length : close + 3;
        ranges.push([lt, end]);
        i = end;
        continue;
      }
      tagAt.lastIndex = lt;
      const hit = tagAt.exec(text);
      if (!hit) {
        i = lt + 1;
        continue;
      }
      const end = tagEnd(text, lt + hit[0].length);
      if (end < 0)
        break;
      i = end + 1;
      if (hit[1] === "/")
        continue;
      const nameEnd = lt + hit[0].length;
      for (const attribute of readAttributes(text.slice(nameEnd, end), nameEnd))
        if (attribute.value?.includes("<"))
          ranges.push([
            attribute.valueStart,
            attribute.valueStart + attribute.value.length
          ]);
      const name = hit[2].toLowerCase();
      if (RAW_TEXT.has(name)) {
        const closer = new RegExp(`</${name}\\s*>`, "gi");
        closer.lastIndex = end + 1;
        const close = closer.exec(text)?.index ?? text.length;
        ranges.push([end + 1, close]);
        i = close;
      }
    }
    let result = "";
    let from = 0;
    for (const [start, end] of ranges) {
      result += text.slice(from, start) + blank(text.slice(start, end));
      from = end;
    }
    return result + text.slice(from);
  }
  var selfClosing = (body) => /(^|[\s"'])\/$/.test(body);
  function tree(source) {
    const nodes = [];
    const stack = [];
    for (const tag of scan(source)) {
      if (tag.closing) {
        let at = stack.length - 1;
        while (at >= 0 && stack[at].name !== tag.name)
          at--;
        if (at >= 0)
          stack.length = at;
        continue;
      }
      const nameStart = tag.start + 1;
      const nameEnd = nameStart + tag.name.length;
      const body = source.slice(nameEnd, tag.end);
      const closes = selfClosing(body);
      const node = {
        name: tag.name,
        nameStart,
        nameEnd,
        attributes: readAttributes(closes ? body.slice(0, -1) : body, nameEnd),
        parent: stack[stack.length - 1]
      };
      nodes.push(node);
      const foreign = tag.name === "svg" || tag.name === "math" || stack.some((n) => n.name === "svg" || n.name === "math");
      if (!VOID.has(tag.name) && !(closes && foreign))
        stack.push(node);
    }
    return nodes;
  }
  function checkReferences(text) {
    const nodes = tree(pageSource(text));
    const findings = [];
    const ids = new Map;
    const labelFor = new Set;
    const describedBy = new Set;
    for (const node of nodes) {
      const id = value(node, "id");
      if (id?.value) {
        const decoded = decode(id.value);
        if (ids.has(decoded)) {
          findings.push({
            start: id.valueStart,
            end: id.valueStart + id.value.length,
            severity: "error",
            link: LINK,
            message: `id="${id.value}" står mer enn én gang på siden. for og ` + "aria-describedby peker da på det første elementet, og koblingen " + "til dette er brutt. Hver id må være unik."
          });
        } else
          ids.set(decoded, node);
      }
      if (node.name === "label") {
        const target = value(node, "for")?.value;
        if (target)
          labelFor.add(decode(target));
      }
      for (const part of decode(value(node, "aria-describedby")?.value ?? "").split(/\s+/))
        if (part)
          describedBy.add(part);
    }
    for (const node of nodes) {
      for (const [name, loses] of Object.entries(REFERENCES)) {
        const attribute = value(node, name);
        if (!attribute?.value)
          continue;
        for (const token of attribute.value.matchAll(/\S+/g)) {
          const target = token[0];
          const at = attribute.valueStart + (token.index ?? 0);
          const found = ids.get(decode(target));
          if (!found) {
            findings.push({
              start: at,
              end: at + target.length,
              severity: "error",
              link: LINK,
              message: `${name}="${attribute.value}" peker på id-en «${target}», som ` + `ikke finnes på siden. Skjermleseren mister ${loses}. ` + (name === "aria-controls" ? "" : HOW)
            });
          } else if (name === "for" && node.name === "label" && !LABELABLE.has(found.name) && !found.name.includes("-")) {
            findings.push({
              start: at,
              end: at + target.length,
              severity: "error",
              link: LINK,
              message: `for="${attribute.value}" peker på et <${found.name}>, som ikke ` + "kan ha en ledetekst. for må peke på feltet selv: <input>, " + `<select>, <textarea> eller en knapp. ${HOW}`
            });
          }
        }
      }
      if (node.name === "a" && within(node, (n) => n.name === "fs-error-summary" || hasClass(n, (c) => c === "fs-error-summary"))) {
        const href = value(node, "href");
        const target = href?.value?.startsWith("#") ? href.value.slice(1) : "";
        if (href && target && !ids.has(fragment(target))) {
          findings.push({
            start: href.valueStart + 1,
            end: href.valueStart + target.length + 1,
            severity: "error",
            link: SUMMARY_LINK,
            message: `Lenken i feiloppsummeringen går til «#${target}», som ikke finnes ` + "på siden. Den skal gå til feltet som feilet, slik at brukeren " + "havner der feilen kan rettes."
          });
        }
      }
      if (within(node, (n) => n.name === "fs-field"))
        continue;
      if ((node.name === "input" || node.name === "textarea" || node.name === "select") && hasClass(node, (c) => c.startsWith("fs-")) && !UNLABELLED_TYPES.has((value(node, "type")?.value ?? "").toLowerCase())) {
        const id = value(node, "id")?.value;
        const named = within(node, (n) => n.name === "fs-suggestion" || n.name === "label") || id && labelFor.has(decode(id)) || value(node, "aria-label") || value(node, "aria-labelledby");
        if (!named) {
          findings.push({
            start: node.nameStart,
            end: node.nameEnd,
            severity: "warning",
            link: LINK,
            message: `<${node.name}> har ingen ledetekst: ingen <label for> som peker på ` + "det, ingen <label> rundt, og verken aria-label eller " + `aria-labelledby. En skjermleser leser feltet opp uten navn. ${HOW}`
          });
        }
      }
      const kind = hasClass(node, (c) => c === "fs-error-text") ? "Feilmeldingen" : hasClass(node, (c) => c === "fs-help-text") ? "Hjelpeteksten" : undefined;
      const live = ["status", "alert"].includes(value(node, "role")?.value ?? "") || value(node, "aria-live") !== undefined;
      if (kind && !live && !isHidden(node)) {
        const id = value(node, "id")?.value;
        if (!id || !describedBy.has(decode(id))) {
          findings.push({
            start: node.nameStart,
            end: node.nameEnd,
            severity: "warning",
            link: LINK,
            message: `${kind} er ikke koblet til noe felt: ` + (id ? `id-en «${id}» står ikke i aria-describedby på noe felt. ` : "den har ingen id, så ingen aria-describedby kan peke på den. ") + `En skjermleser leser den ikke opp sammen med feltet. ${HOW}`
          });
        }
      }
    }
    return findings.sort((a, b) => a.start - b.start);
  }

  // designsystem/src/diagnostics/index.ts
  function diagnoseMarkup(text) {
    return diagnose(text, elements, classes);
  }
  function diagnosePage(text, elementList = elements, classList = classes) {
    const page = pageSource(text);
    return [
      ...diagnose(page, elementList, classList),
      ...checkReferences(page)
    ].sort((a, b) => a.start - b.start);
  }

  // jvm/scripts/inngang.ts
  Object.assign(globalThis, {
    FristilDiagnostikk: { diagnoseMarkup, diagnosePage }
  });
